async def upgrade(db: BaseDBAsyncClient) -> str:
    """KEY-317 — 절에 **보이는 차례**를 주고, 차례 변경을 감사에 남긴다.

    ① `guide_section.display_order` 를 더하고
    ② **이미 있는 안내문을 계약 차례로 채운다** — 이 줄이 빠지면 옛 안내문의
       절이 전부 `-1` 이 되어 차례가 무너진다. 응급 문장이 어디에 설지 알 수
       없게 된다는 뜻이다.
    ③ 사건에 이전·이후 차례 칸을 더하고
    ④ 사건 갈래에 `SECTION_REORDERED` 를 넣는다

    `FIELD()` 는 목록에서 몇 번째인지를 1 부터 준다. 계약 차례는 0 부터라
    하나를 뺀다. 이 다섯은 `GuideSectionKey` 전부다 — 여섯째가 생기면
    `app/tests/guide_apis/test_key317_section_order.py` 가 먼저 운다.
    """
    return """
        ALTER TABLE `guide_section` ADD `display_order` INT NOT NULL DEFAULT -1 COMMENT '보이는 차례 — KEY-317';
        UPDATE `guide_section` SET `display_order` =
            FIELD(`section_key`, 'medication', 'caution', 'emergency', 'life', 'messages') - 1;
        ALTER TABLE `guide_event` ADD `order_before` VARCHAR(200) COMMENT '차례를 바꾸기 전 — KEY-317';
        ALTER TABLE `guide_event` ADD `order_after` VARCHAR(200) COMMENT '차례를 바꾼 뒤 — KEY-317';
        ALTER TABLE `guide_event` MODIFY COLUMN `event_type` VARCHAR(17) NOT NULL;"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    """되돌리면 **차례가 계약 차례로 돌아간다.**

    사람이 정한 차례는 이 컬럼에만 있어서 함께 사라진다. 되돌릴 일이 있으면
    그전에 `SELECT guide_document_id, section_key, display_order FROM guide_section`
    을 떠 둔다 — 감사 사건의 `order_after` 로도 되짚을 수 있다.
    """
    return """
        ALTER TABLE `guide_event` MODIFY COLUMN `event_type` VARCHAR(13) NOT NULL;
        ALTER TABLE `guide_event` DROP COLUMN `order_after`;
        ALTER TABLE `guide_event` DROP COLUMN `order_before`;
        ALTER TABLE `guide_section` DROP COLUMN `display_order`;"""


